"""Freeze the display-ready figure-data package for the six-figure RSE package.

Phase 1 of ``paper/notes/six_figure_plan.md`` section 13: create
``paper/data/final/figures/`` and populate the frozen display tables plus
``fig_manifest.json``.

This module is a read-only transformation of already-archived evaluator
artifacts, plus one newly specified whole-field bootstrap (Fig. 6 panel d).
It never opens a calibration, never reruns a forward model, and never issues an
Earth Engine request.  The only containers it touches are opened read-only.

Legacy -> current experiment mapping (recorded once in the manifest and written
into every table):

    legacy ``e2_*`` / repository ``examples/5_Flux_Ensemble``  -> current E1
    legacy ``e3_*`` / repository ``examples/6_Flux_International`` -> current E2
    legacy ``e4_*`` / repository ``examples/7_Applied_Water``  -> current E3

The legacy ``e1_*`` artifacts belong to the removed broad-land-cover experiment
and are never read here.

This file is the command line only.  The builders live in ``figdata/``: one
module per figure (``fig01_scope`` + ``fig01_architecture``, ``fig02_formulation``,
``fig03_agreement``, ``fig04_reliability``, ``fig05_transfer``,
``fig06_applied_water``) over the shared ``paths``, ``cohorts``, ``manifest`` and
``sources`` modules.  ``--check`` re-hashes the sources the manifest records;
``figdata.compare`` and ``tests/regression/test_figure_package_build.py`` hold a
rebuild to the frozen package byte for byte.

Usage::

    uv run python scripts/figures/build_figure_data.py --all
    uv run python scripts/figures/build_figure_data.py --only fig06_bootstrap
    uv run python scripts/figures/build_figure_data.py --check
"""

import argparse
import sys
from pathlib import Path

from figdata import paths
from figdata.check import check_sources
from figdata.fig01_scope import build_fig01
from figdata.fig02_formulation import build_fig02, build_fig02_bootstrap
from figdata.fig03_agreement import build_fig03
from figdata.fig04_reliability import build_fig04
from figdata.fig05_transfer import build_fig05_e1, build_fig05_e2
from figdata.fig06_applied_water import build_fig06, build_fig06_bootstrap
from figdata.manifest import MANIFEST

# --------------------------------------------------------------------------
# driver
# --------------------------------------------------------------------------

BUILDERS = {
    "fig01": build_fig01,
    "fig02": build_fig02,
    "fig02_bootstrap": build_fig02_bootstrap,
    "fig03": build_fig03,
    "fig04": build_fig04,
    "fig05_e1": build_fig05_e1,
    "fig05_e2": build_fig05_e2,
    "fig06": build_fig06,
    "fig06_bootstrap": build_fig06_bootstrap,
}

# fig01 consumes the frozen fig03 example series (retained Figure 1 provenance,
# re-registered but never regenerated by build_fig03) and fig04 capture values,
# so a --all run must build it last.  Every other builder is independent.
BUILD_ORDER = [
    "fig02",
    "fig02_bootstrap",
    "fig03",
    "fig04",
    "fig05_e1",
    "fig05_e2",
    "fig06",
    "fig06_bootstrap",
    "fig01",
]
if set(BUILD_ORDER) != set(BUILDERS):
    raise RuntimeError("BUILD_ORDER and BUILDERS disagree")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--all", action="store_true", help="build every table")
    ap.add_argument("--only", action="append", choices=sorted(BUILDERS), default=None)
    ap.add_argument("--out", default=str(paths.OUT))
    ap.add_argument(
        "--check",
        action="store_true",
        help="re-hash the sources fig_manifest.json records instead of building",
    )
    args = ap.parse_args(argv)

    paths.OUT = Path(args.out)
    if args.check:
        n, problems = check_sources(paths.OUT / "fig_manifest.json", repo=paths.REPO)
        for line in problems:
            print(f"  {line}", file=sys.stderr)
        print(f"checked {n} recorded sources; {len(problems)} changed or missing")
        return 1 if problems else 0
    paths.OUT.mkdir(parents=True, exist_ok=True)

    if args.only:
        targets = sorted(set(args.only), key=BUILD_ORDER.index)
        MANIFEST.partial_targets = targets
    elif args.all:
        targets = list(BUILD_ORDER)
    else:
        targets = None
    if targets is None:
        ap.error("pass --all or --only NAME")

    failures = []
    for name in targets:
        print(f"[{name}]")
        try:
            BUILDERS[name]()
        except Exception as exc:  # noqa: BLE001 - reported, then recorded
            failures.append((name, f"{type(exc).__name__}: {exc}"))
            print(f"  FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
            MANIFEST.block(name, f"{type(exc).__name__}: {exc}")

    p = MANIFEST.write()
    print(f"\nmanifest: {p}")
    if failures:
        print(f"{len(failures)} builder(s) failed; see BUILD_STATUS.md", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
